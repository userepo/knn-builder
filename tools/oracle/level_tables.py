"""Writes the level-table test data for knn-write: what Faiss's HNSW holds
for every M the service can produce, computed by levels.py.

Usage: python level_tables.py OUT
  OUT  crates/knn-write/tests/data/level_tables.txt

Run it in the faiss-base-snapshot image (tools/README.md): the
probabilities go through the C library's exp, and the service's files were
written with glibc's. The first line is a comment; every other is one of
  probas <M> <f64 bits as hex>...          assign_probas
  cum <M> <i32>...                         cum_nneighbor_per_level
  levels <M> <n> <slots> <checksum> <count>...
where `levels` describes the level table of n nodes: slots is the length
of the neighbors array (offsets[n]), checksum the sum over nodes of
(i + 1) x stored level, modulo 2^64, and the counts the nodes at each
stored level from 1.
"""

import pathlib
import struct
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from levels import default_probas, level_table  # noqa: E402

# M = graph degree / 2 = 2m for the service's degree of m x 4. k-NN only
# requires m > 0; m up to 2048 (degree 8192) is far past any practical
# setting, and knn-write's tables are verified this far and no further.
M_VALUES = range(2, 4097, 2)
# M for the level histograms: the fixtures' 32 and 14, the smallest, and a
# spread of others.
LEVEL_M = (2, 4, 14, 32, 64, 128, 512)
# Enough nodes to reach draws where computing the draw in double instead of
# Faiss's float changes a level: the first such node is 1,089,903 for
# M = 2, 1,518,146 for M = 32, 1,799,631 for M = 14 and 2,082,501 for M = 4.
LEVEL_N = 2_100_000


def main():
    out = pathlib.Path(sys.argv[1])
    lines = ["# Generated by tools/oracle/level_tables.py; do not edit."]
    for m in M_VALUES:
        probas, cum = default_probas(m)
        bits = [f"{struct.unpack('<Q', struct.pack('<d', p))[0]:016x}" for p in probas]
        lines.append(f"probas {m} " + " ".join(bits))
        lines.append(f"cum {m} " + " ".join(str(c) for c in cum))
    for m in LEVEL_M:
        _, _, levels, offsets = level_table(LEVEL_N, m)
        weights = np.arange(1, LEVEL_N + 1, dtype=np.uint64)
        checksum = int((weights * levels.astype(np.uint64)).sum(dtype=np.uint64))
        counts = np.bincount(levels)[1:]
        lines.append(
            f"levels {m} {LEVEL_N} {int(offsets[-1])} {checksum} " + " ".join(str(int(c)) for c in counts)
        )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(("\n".join(lines) + "\n").encode())
    print(f"wrote {out}: {len(M_VALUES)} M values, levels for M in {LEVEL_M}")


if __name__ == "__main__":
    main()
