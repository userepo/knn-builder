"""Writes knn-gpu's test data from the upstream service's own code: the
build parameters it derives from a request, and its fp32 to fp16
conversion.

Usage: python build_tables.py OUT_DIR
  OUT_DIR  crates/knn-gpu/tests/data

Run it in the api-snapshot image (tools/README.md), where the service's
Python package and numpy are importable from /app. Writes
  params.txt  `m <m>...` once, the requested m values; then
              `n <doc_count> <n_lists> <effective m>...`, one effective m per
              requested m, in that order; then `pq <dimension> <pq_dim>`
  fp16.txt    `<f32 bits> <f16 bits>` in hex: the value and the float16
              the service stores for it
The first line of each file is a comment.
"""

import pathlib
import sys

import numpy as np

sys.path.insert(0, "/app/remote_vector_index_builder")
from core.common.models.index_builder.faiss.ivf_pq_search_cagra_config import (  # noqa: E402
    IVFPQSearchCagraConfig,
)
from core.index_builder.faiss.faiss_index_build_service import (  # noqa: E402
    FaissIndexBuildService,
)
from core.index_builder.index_builder_utils import (  # noqa: E402
    calculate_effective_m,
    calculate_ivf_pq_n_lists,
)

M_VALUES = (1, 2, 3, 4, 8, 16, 24, 32, 48, 64, 96, 128)
# Every count up to 3,000, then a stride up to 60,000 (m = 128 is lowered
# up to about 42,000), then a spread of larger counts with squares and
# their neighbors (the truncated square root's edges), up to the largest
# 32-bit count.
DOC_COUNTS = sorted(
    set(range(5, 3001))
    | set(range(3001, 60_001, 97))
    | {10**k for k in range(5, 10)}
    | {s * s + d for s in (99, 1000, 4096, 46340) for d in (-1, 0, 1)}
    | {2**31 - 1}
)
DIMENSIONS = (1, 2, 3, 4, 5, 7, 8, 63, 64, 127, 128, 384, 768, 1536, 4096)


def params():
    n_probes = IVFPQSearchCagraConfig.n_probes
    factor = FaissIndexBuildService().PQ_DIM_COMPRESSION_FACTOR
    lines = ["# Generated by tools/oracle/build_tables.py from the service's code; do not edit."]
    lines.append("m " + " ".join(map(str, M_VALUES)))
    for doc_count in DOC_COUNTS:
        n_lists = calculate_ivf_pq_n_lists(doc_count)
        effective = [calculate_effective_m(m, doc_count, n_lists, n_probes) for m in M_VALUES]
        lines.append(f"n {doc_count} {n_lists} " + " ".join(map(str, effective)))
    # faiss_index_build_service.py: int(dimension / PQ_DIM_COMPRESSION_FACTOR)
    lines += [f"pq {dim} {int(dim / factor)}" for dim in DIMENSIONS]
    return lines


def fp16():
    rng = np.random.default_rng(16)
    edges = np.array(
        [0.0, -0.0, 1.0, -1.0, 65504.0, 65519.99, 65520.0, 1e9, -1e9, np.inf, -np.inf,
         6.1035156e-05, 6.0975552e-05, 5.9604645e-08, 2.9802322e-08, 2.9802326e-08, 1e-10,
         1.0009765625, 1.00048828125, 1.000732421875, 0.1, 1 / 3],
        dtype=np.float32,
    )
    random = rng.integers(0, 2**32, size=5_000, dtype=np.uint64).astype(np.uint32).view(np.float32)
    normal = rng.standard_normal(2_000).astype(np.float32)
    values = np.concatenate([edges, random, normal])
    # k-NN rejects NaN vectors, so NaN payloads are not part of the contract.
    values = values[~np.isnan(values)]
    out = np.zeros(len(values), dtype=np.float16)
    with np.errstate(over="ignore"):  # values past float16 become infinity
        out[:] = values  # as FP32ToFP16ConvertingBytesIO assigns them
    lines = ["# Generated by tools/oracle/build_tables.py: f32 bits, numpy's f16 bits."]
    lines += [f"{a:08x} {b:04x}" for a, b in zip(values.view(np.uint32), out.view(np.uint16))]
    return lines


def main():
    out = pathlib.Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    for name, lines in (("params.txt", params()), ("fp16.txt", fp16())):
        (out / name).write_bytes(("\n".join(lines) + "\n").encode())
        print(f"wrote {out / name}: {len(lines) - 1} lines")


if __name__ == "__main__":
    main()
